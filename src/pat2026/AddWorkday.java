    private void btnSubmitActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSubmitActionPerformed
        try {
            String workerCode = txtf10.getText().trim().toUpperCase();

            if (workerCode.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Please enter a worker code.");
                return;
            }

            if (!workerExists(workerCode)) {
                JOptionPane.showMessageDialog(this, "No worker with the code " + workerCode + " exists.");
                return;
            }

            LocalDate date = LocalDate.of(
                    Integer.parseInt(txtEditStartYear.getText().trim()),
                    Integer.parseInt(txtEditStartMonth.getText().trim()),
                    Integer.parseInt(txtEditStartDay.getText().trim()));

            int startHour = Integer.parseInt(txtf1.getText().trim());
            int startMinute = Integer.parseInt(txtf2.getText().trim());
            int lunchStartHour = Integer.parseInt(txtf3.getText().trim());
            int lunchStartMinute = Integer.parseInt(txtf4.getText().trim());
            int lunchEndHour = Integer.parseInt(txtf5.getText().trim());
            int lunchEndMinute = Integer.parseInt(txtf6.getText().trim());
            int endHour = Integer.parseInt(txtf7.getText().trim());
            int endMinute = Integer.parseInt(txtf8.getText().trim());
            int rows = Integer.parseInt(txtf9.getText().trim());

            // LocalTime.of also rejects invalid values (hour 25, minute 70, etc.)
            LocalTime start = LocalTime.of(startHour, startMinute);
            LocalTime lunchStart = LocalTime.of(lunchStartHour, lunchStartMinute);
            LocalTime lunchEnd = LocalTime.of(lunchEndHour, lunchEndMinute);
            LocalTime end = LocalTime.of(endHour, endMinute);

            if (date.isAfter(LocalDate.now())) {
                JOptionPane.showMessageDialog(this, "The date worked cannot be in the future.");
            }

            if (start.isAfter(lunchStart) || lunchStart.isAfter(lunchEnd) || lunchEnd.isAfter(end)
                    || !start.isBefore(end)) {
                JOptionPane.showMessageDialog(this,
                        "The times must be in order: start, lunch start, lunch end, end.");
                return;
            }

            if (rows < 0) {
                JOptionPane.showMessageDialog(this, "Rows done cannot be negative.");
                return;
            }

            String typeOfWork = (String) jComboBox1.getSelectedItem();
            if (typeOfWork == null || typeOfWork.isBlank()) {
                JOptionPane.showMessageDialog(this, "Please choose or enter a work type.");
                return;
            }

            CreateWorkday workday = new CreateWorkday();

            workday.setDate(date);
            workday.setStartHour(startHour);
            workday.setStartMinute(startMinute);
            workday.setLunchStartHour(lunchStartHour);
            workday.setLunchStartMinute(lunchStartMinute);
            workday.setLunchEndHour(lunchEndHour);
            workday.setLunchEndMinute(lunchEndMinute);
            workday.setEndHour(endHour);
            workday.setEndMinute(endMinute);
            workday.setTypeOfWork(typeOfWork.trim());
            workday.setRowsDone(rows);

            workday.logWorkday(workerCode);

            JOptionPane.showMessageDialog(this, "Workday logged successfully for " + workerCode + "!");
            this.dispose(); // closes the dialog

        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this, "Please enter numbers only in the time and rows fields.");
        } catch (java.time.DateTimeException ex) {
            JOptionPane.showMessageDialog(this, "Please enter a valid hour (0-23) and minute (0-59).");
        } catch (IOException ex) {
            JOptionPane.showMessageDialog(this, "Error saving workday: " + ex.getMessage());
        }
    }//GEN-LAST:event_btnSubmitActionPerformed

