    // Checks the typed code against the real workers in WorkerDetails.txt
    private boolean workerExists(String code) throws IOException {
        GetWorkers fetcher = new GetWorkers();

        if (fetcher.getWorkerData()) {
            Worker[] workers = fetcher.getWorkers();

            for (int i = 0; i < fetcher.getCount(); i++) {
                if (workers[i].getWorkerCode().equalsIgnoreCase(code)) {
                    return true;
                }
            }
        }
        return false;
    }

