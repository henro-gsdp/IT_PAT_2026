    private void tblWorkerMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblWorkerMouseClicked

        int row = tblWorker.rowAtPoint(evt.getPoint());
        int col = tblWorker.columnAtPoint(evt.getPoint());

        if (row < 0) {
            return; // clicked on empty space
        }

        String workerCode = tblWorker.getValueAt(row, 0).toString();

        if (col == 3) {
            btnWorkerDetails(workerCode);
        } else if (col == 4) {
            btnWorkdays(workerCode);
        }
    }

    private void btnWorkerDetails(String workerCode) {
        ViewEditWorkerInfo dialog = new ViewEditWorkerInfo(this, true, workerCode);
        dialog.setVisible(true);
        DisplayDetails(); // refresh after edits
    }

    private void btnWorkdays(String workerCode) {
        ViewEditWorkdays dialog = new ViewEditWorkdays(this, true, workerCode);
        dialog.setVisible(true);
        DisplayDetails();
    }//GEN-LAST:event_tblWorkerMouseClicked

    private void btnLogOutActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLogOutActionPerformed
        int choice = JOptionPane.showConfirmDialog(this,
                "Are you sure you want to log out?", "Log Out", JOptionPane.YES_NO_OPTION);

        if (choice == JOptionPane.YES_OPTION) {
            LoginPage login = new LoginPage();
            login.setVisible(true);
            this.dispose();
        }
    }//GEN-LAST:event_btnLogOutActionPerformed

