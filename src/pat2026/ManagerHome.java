    private void DisplayDetails() {
        DefaultTableModel model = (DefaultTableModel) tblWorker.getModel();
        model.setRowCount(0); // clears the empty placeholder row from the designer

        try {
            GetWorkers workerFetcher = new GetWorkers();

            if (workerFetcher.getWorkerData()) {
                workers = workerFetcher.getWorkers();
                workerCount = workerFetcher.getCount();

                for (int i = 0; i < workerCount; i++) {
                    Object[] row = {
                        workers[i].getWorkerCode(),
                        workers[i].getName() + " " + workers[i].getSurname(),
                        workers[i].getStatus(),
                        "View / Edit",
                        "View / Edit"
                    };
                    model.addRow(row);
                }
            } else {
                JOptionPane.showMessageDialog(this, "No workers have been captured yet.");
            }

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this,
                    "Could not load worker records: " + e.getMessage());
        }

    }

